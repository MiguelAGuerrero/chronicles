// Learns the place-form territories from the confirmed calibration places (specs/place-form PF28) and writes src/lib/walk/placeFormTerritories.ts. It also
// prints the leave-one-out result of the whole rule (each place judged by territories learned without it, with the same stability gate), the number the
// owner reads before a held-out look. Deterministic: the same fixtures give the same file.
//
//   npm run learn:place-form          (writes the table)   |   npm run learn:place-form -- --check   (prints only)
import { writeFileSync } from 'node:fs';
import { acceptable, loadSet, readOf } from '../src/lib/__tests__/walkability/placeFormFixtures';
import { STABILITY_NEED } from '../src/lib/walk/placeForm';
import { learnTerritories, MARGIN, WORD_IDS } from '../src/lib/walk/placeFormLearn';
import { FEATURES, inTerritory } from '../src/lib/walk/placeFormTerritory';
import { measureRings } from '../src/lib/walk/placeSignals';

const set = loadSet('Calibration');
const rows = set.places.map((p) => ({ p, rings: measureRings(readOf(p)) })).filter((r) => r.rings[0]);
const labelled = (list) => list.map((r) => ({ id: r.p.id, word: r.p.word, accept: r.p.accept, m: r.rings[0] }));
const wordIn = (t, m) => {
  if (!m) return null;
  const hits = WORD_IDS.filter((w) => t[w] && inTerritory(t[w], m));
  return hits.length === 1 ? hits[0] : null;
};
const wordOf = (t, rings) => {
  const w = wordIn(t, rings[0]);
  return w && rings.filter((m) => wordIn(t, m) === w).length >= STABILITY_NEED ? w : null;
};

// Leave-one-out: judge each place by territories learned without it.
let spoke = 0, right = 0, falsePos = 0, wrong = 0, asked = 0, got = 0;
const bad = [];
for (let i = 0; i < rows.length; i++) {
  const t = learnTerritories(labelled(rows.filter((_, j) => j !== i)));
  const g = wordOf(t, rows[i].rings);
  const ok = acceptable(rows[i].p).includes(g);
  if (g) {
    spoke++;
    if (ok) right++;
    else {
      if (rows[i].p.word === null) falsePos++;
      else wrong++;
      bad.push(`${rows[i].p.id}(${rows[i].p.word}->${g})`);
    }
  }
  if (rows[i].p.word !== null && !acceptable(rows[i].p).includes(null)) {
    asked++;
    if (g && ok) got++;
  }
}
console.log(`leave-one-out over ${rows.length} places: spoke ${spoke}, right ${right}, false positives ${falsePos}, wrong word ${wrong}; recall ${got}/${asked} = ${(got / asked).toFixed(2)}`);
if (bad.length) console.log('  wrong:', bad.join(' '));

const territories = learnTerritories(labelled(rows));
const fmt = (v) => (v === null ? 'null' : String(v));
const lines = WORD_IDS.map((w) => {
  const t = territories[w];
  if (!t) return `  ${w}: null,`;
  return `  ${w}: {\n${FEATURES.map((f) => `    ${f}: { lo: ${fmt(t[f].lo)}, hi: ${fmt(t[f].hi)} },`).join('\n')}\n  },`;
});
const src = `// @layer core
import type { FormWord } from './placeForm';
import type { Territory } from './placeFormTerritory';

/*
 * GENERATED by \`npm run learn:place-form\` (specs/place-form PF28) from ${rows.length} confirmed real places, margin ${MARGIN}; do not edit by hand.
 * A territory is a box over the measures, in the measures' own units (counts per km², metres, shares); null is open. A place has a word only inside exactly one
 * of them and when the ring read from 150 m around it agrees (placeForm.ts).
 */
export const TERRITORIES: Record<FormWord, Territory | null> = {
${lines.join('\n')}
};
`;
if (!process.argv.includes('--check')) {
  writeFileSync(new URL('../src/lib/walk/placeFormTerritories.ts', import.meta.url), src);
  console.log('wrote src/lib/walk/placeFormTerritories.ts');
}
